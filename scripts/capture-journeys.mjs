import { chromium } from '@playwright/test'
import fs from 'node:fs/promises'

const out = '.hallmark/journeys'
await fs.mkdir(out, { recursive: true })
const browser = await chromium.launch()
let captures = 0
for (const [name, width, height] of [['phone', 390, 844], ['desktop', 1280, 900]]) {
  const context = await browser.newContext({ viewport: { width, height }, reducedMotion: 'reduce', serviceWorkers: 'allow', locale: 'en-US' })
  const page = await context.newPage()
  await page.route('**/.netlify/functions/discover', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Offline visual-review fixture' }) }))
  const shot = async (label, fullPage = true) => { await page.screenshot({ path: `${out}/${name}-${label}.png`, fullPage }); captures += 1 }
  for (const route of ['today', 'explore', 'vault', 'review', 'profile']) {
    await page.goto(`http://localhost:4173/#/${route}`)
    await page.locator('main#main').waitFor()
    await page.evaluate(() => document.fonts.ready)
    await shot(route)
  }
  await page.goto('http://localhost:4173/#/explore?path=phone-eye')
  await page.getByRole('heading', { level: 1 }).waitFor()
  await shot('cinema-path')
  await page.getByRole('button', { name: 'Add to my daily mix' }).click()
  await page.locator('.explore-results .lesson-card-main').first().click()
  const dialog = page.getByRole('dialog')
  await dialog.waitFor()
  await shot('reader-understand', false)
  await dialog.getByRole('button', { name: 'Try this idea', exact: true }).click()
  await dialog.getByRole('textbox', { name: /Your note or experiment/ }).fill('Visual review sample: compare the same doorway from two camera heights.')
  await dialog.getByRole('button', { name: 'Plan this experiment', exact: true }).click()
  await dialog.getByRole('button', { name: 'Save this bite', exact: true }).click()
  await shot('reader-experiment', false)
  await dialog.getByRole('button', { name: 'Test my recall', exact: true }).click()
  await dialog.getByRole('radio').first().check()
  await dialog.getByRole('button', { name: 'Check my answer', exact: true }).click()
  await shot('reader-feedback', false)
  await dialog.getByRole('button', { name: 'Complete bite', exact: true }).click()
  await shot('reader-complete', false)
  await dialog.getByRole('button', { name: 'Close lesson', exact: true }).click()
  await page.goto('http://localhost:4173/#/vault?view=notes')
  await page.getByRole('heading', { level: 1 }).waitFor()
  await shot('vault-with-note')
  await page.goto('http://localhost:4173/#/vault?view=practice')
  await page.getByRole('heading', { level: 1 }).waitFor()
  await shot('practice-planned')
  await page.getByRole('button', { name: 'Mark as tried', exact: true }).click()
  await shot('practice-tried')
  await page.goto('http://localhost:4173/#/explore?path=phone-detail&lesson=fg-013')
  await page.getByRole('dialog').getByRole('button', { name: 'Try this idea', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Close lesson', exact: true }).click()
  await page.goto('http://localhost:4173/#/vault?view=unfinished')
  await page.getByRole('heading', { level: 1 }).waitFor()
  await shot('unfinished')
  await page.locator('.lesson-card-main').click()
  await shot('reader-resumed', false)
  await page.getByRole('dialog').getByRole('button', { name: 'Close lesson', exact: true }).click()
  await page.goto('http://localhost:4173/#/profile')
  await page.getByRole('heading', { level: 1 }).waitFor()
  await shot('profile-with-progress')
  await page.getByRole('button', { name: 'How UNSCROLL works', exact: true }).click()
  for (const stage of ['lesson', 'topics', 'pace']) {
    await shot(`setup-${stage}`, false)
    if (stage !== 'pace') await page.locator('.onboarding-dialog').getByRole('button', { name: 'Continue', exact: true }).click()
  }
  await page.locator('.onboarding-dialog').getByRole('button', { name: 'Close setup without saving', exact: true }).click()
  await page.getByRole('button', { name: 'Offline and updates', exact: true }).click()
  await shot('offline-settings', false)
  await page.goto('http://localhost:4173/#/explore?lesson=cinema-027')
  const bounce = page.locator('.reader-dialog')
  await bounce.locator('.teaching-image').first().scrollIntoViewIfNeeded()
  await shot('bounce-illustration', false)
  await bounce.getByRole('button', { name: /^Enlarge diagram:/ }).first().click()
  await shot('bounce-enlarged', false)
  await page.locator('.visual-viewer[open]').getByRole('button', { name: 'Close enlarged diagram' }).click()
  await bounce.getByRole('button', { name: 'Close lesson', exact: true }).click()
  await page.goto('http://localhost:4173/#/explore?lesson=design-031')
  await page.locator('.reader-dialog .teaching-image').first().scrollIntoViewIfNeeded()
  await shot('route-status-illustration', false)
  await page.locator('.reader-dialog').getByRole('button', { name: 'Close lesson', exact: true }).click()
  await page.goto('http://localhost:4173/#/profile')
  await page.getByRole('radio', { name: 'Larger text', exact: true }).check()
  await page.getByRole('region', { name: 'Preferences', exact: true }).getByText('Larger lesson text saved.', { exact: true }).waitFor()
  await page.goto('http://localhost:4173/#/explore?lesson=money-003')
  await page.locator('.reader-dialog .teaching-section').first().scrollIntoViewIfNeeded()
  await shot('larger-reading', false)
  await context.close()
}
await browser.close()
console.log(`Captured ${captures} desktop/phone route and reader-state images in .hallmark/journeys. Sample notes are only in isolated review contexts.`)